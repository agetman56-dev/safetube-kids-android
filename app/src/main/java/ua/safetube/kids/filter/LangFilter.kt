package ua.safetube.kids.filter

/**
 * Визначення мови тексту. Порт перевіреного алгоритму з розширення SafeTube UA
 * (`lang.js`), доповнений дитячою лексикою.
 *
 * Чому переписано з нуля, а не лишили попередній варіант:
 *
 * 1. Попередня версія ховала 43% українського дитячого контенту. На наборі з
 *    23 типових назв («Казка про кота у чоботях», «Колискова для малят»,
 *    «Пригоди Патрона») вона приховувала 10. Причина — правило «кирилиця без
 *    літер і, ї, є, ґ = російська»: українські дитячі назви часто цих літер
 *    не містять.
 *
 * 2. У попередній версії був вираз Regex("ии|ие|ое\\b|ый\\b"). Межа слова \b
 *    і в Java, і в JavaScript рахує «літерами» лише латиницю, тому частини
 *    «ое\b» та «ый\b» не спрацьовували жодного разу. Тут скрізь (?![\p{L}]),
 *    що з кирилицею працює правильно.
 *
 * 3. У списку російських слів стояло «серіал» — українське написання.
 *
 * Важливо про баланс помилок саме в цьому застосунку: канал уже схвалений
 * батьком, тому приховати відео зі схваленого каналу — чиста втрата, а
 * пропустити сумнівне — дрібниця. Тому за замовчуванням суворий режим ВИМКНЕНО
 * (на відміну від розширення, яке працює з невідомими каналами).
 */
object LangFilter {

    private val RU_LETTERS = Regex("[ыъэё]")          // немає в українській
    private val UA_LETTERS = Regex("[іїєґ]")          // немає в російській

    private const val END = "(?![\\p{L}])"            // «кінець слова» для кирилиці

    /** Закінчення, характерні для російської і відсутні в українській. */
    private val RU_MORPH = listOf(
        "ое$END",        // новое / большое     (укр. «нове»)
        "ая$END",        // красная             (укр. «червона»)
        "яя$END",        // утренняя
        "ется$END",      // делается            (укр. «робиться»)
        "ешь$END", "ишь$END",
        "ание$END",      // задание             (укр. «завдання»)
        "ение$END",      // обучение            (укр. «навчання»)
        "ский$END", "ская$END", "ское$END",
        "ать$END",       // делать              (укр. «робити»)
        "ить$END", "еть$END",
        "ой$END",        // водой               (укр. «водою»)
        "ему$END",
        "(?<![\\p{L}])и$END",   // сполучник «и»  (укр. «і», «й», «та»)
        "ющ", "ящ"
    ).map { Regex(it) }

    /** Закінчення, характерні для української і відсутні в російській. */
    private val UA_MORPH = listOf(
        "ання$END",      // прибирання
        "ення$END",
        "ати$END", "ити$END", "увати$END",   // інфінітиви (рос. «-ать/-ить»)
        "имо$END",       // робимо
        "ою$END",        // водою
        "ють$END",       // малюють             (рос. «-ют», без ь)
        "ський$END", "ська$END", "ське$END"
    ).map { Regex(it) }

    // Слова, що існують лише в одній мові. Форми з ы/ъ/э/ё сюди не додаємо —
    // їх і так ловить перевірка літер. Слова, спільні для обох мов («мама»,
    // «кота», «машинки», «каша», «шапочка», «мишка»), навмисно не включені:
    // вони давали б хибні спрацювання.
    private val RU_WORDS: Set<String> = (
        "что как это очень сегодня сейчас если когда здесь есть тоже также потому " +
        "сколько никогда всегда конечно наверное только даже вместе вместо вокруг " +
        "около после между среди чтобы надо нужно можно нельзя который много больше " +
        "меньше лучше хорошо плохо будет может делать делаем делает сказать сказал " +
        "смотреть смотрим видеть вижу идти иду наши его их меня тебя себя обзор " +
        "новости деньги война город страна год года утро утром вечер ночь ребенок " +
        "дети мальчик девочка девушка женщина мужчина друзья игра играем готовить " +
        "готовим рисовать рисуем строить строим дом еда вкусно песня сказка история " +
        "задание итоги главное последние победа враг оружие помощь безопасность " +
        "совет советы русский россия российский сериал время человек жизнь любовь " +
        "уборка тренировка распаковка обучение вопрос ответ сделать первый второй " +
        "дома зала кухни минут минуты недели вечером ночью посмотреть быстро " +
        "здоровье комната машин детская детский " +
        // дитяча лексика
        "детей детям малыш малыша малышам мультфильм мультфильмы учим считаем " +
        "цвета цветами песенка песенки сказки сказку сапогах кукла куклы зайка " +
        "азбука алфавит буквы цифры развивающие развивающий поиграем нарисуем " +
        "приключения любимые веселые добрые зимняя дождик капельки тракторы"
        ).split(" ").toSet()

    private val UA_WORDS: Set<String> = (
        // «та» — український сполучник; російською «и». Сильний і частий маркер.
        "та що як це цей ця які який яка якщо коли зараз дуже вже або але тільки лише " +
        "разом майже щоб аби кожен багато краще добре треба буде був була було були " +
        "має мають робити зробити робимо роблять дивитися дивимось бачу йду його " +
        "огляд новини гроші війна місто країна рік року ранок ранку вечір ніч " +
        "дитина діти хлопець дівчина жінка чоловік друзі гра граємо готувати " +
        "готуємо малювати малюємо будувати будуємо будинок їжа смачно смачна " +
        "страва пісня казка історія завдання підсумки головне останні перемога " +
        "ворог зброя допомога безпека порада поради український українська україна " +
        "серіал час людина життя любов прибирання тренування розпакування навчання " +
        "питання відповідь перший другий вдома авто світ хвилин хвилини тижня " +
        "тиждень швидко найкращий новий кімната кухні дитячий дитяча " +
        // дитяча лексика — пари до російських слів вище
        "казки казку колискова вчимо кольори лічимо абетка цифри " +
        "поросятка дощик крапельки зимова трактори чоботях пригоди улюблена " +
        "улюблені веселі добрі малята малят намалюємо пограємо мультфільм"
        ).split(" ").toSet()

    private val WORD_SPLIT = Regex("[^а-яёіїєґ'ʼ’]+", RegexOption.IGNORE_CASE)
    private val CYR_LETTER = Regex("[а-яёіїєґ]", RegexOption.IGNORE_CASE)

    enum class Lang { UA, RU, OTHER, UNKNOWN }

    private data class Score(val ru: Int, val ua: Int, val cyrWords: Int)

    private fun score(text: String): Score {
        val low = text.lowercase()
        var ru = 0
        var ua = 0

        if (RU_LETTERS.containsMatchIn(low)) ru += 5
        if (UA_LETTERS.containsMatchIn(low)) ua += 5

        for (r in RU_MORPH) if (r.containsMatchIn(low)) ru += 2
        for (r in UA_MORPH) if (r.containsMatchIn(low)) ua += 2

        val words = low.split(WORD_SPLIT).filter { it.length > 1 }
        for (w in words) {
            if (w in RU_WORDS) ru++
            if (w in UA_WORDS) ua++
        }
        return Score(ru, ua, words.count { CYR_LETTER.containsMatchIn(it) })
    }

    /** UA / RU / OTHER (без кирилиці) / UNKNOWN (кирилиця є, але впевненості немає). */
    fun detectLang(text: String): Lang {
        if (text.isBlank()) return Lang.OTHER
        val s = score(text)
        if (s.cyrWords == 0) return Lang.OTHER
        val diff = s.ru - s.ua
        return when {
            diff >= 2 -> Lang.RU
            diff <= -2 -> Lang.UA
            else -> Lang.UNKNOWN
        }
    }

    /**
     * Головна точка входу. Порядок джерел — від найнадійнішого:
     *
     * 1. Мова, яку вказав сам автор відео (defaultAudioLanguage з YouTube API).
     *    Приходить безкоштовно в тій самій відповіді, яку ми вже робимо.
     * 2. Аналіз тексту назви й опису.
     *
     * @param strict якщо true, ховаємо ще й те, що не вдалося визначити впевнено.
     *        За замовчуванням false: канал уже схвалений батьком, тому зайва
     *        суворість лише зрізає хороший контент.
     */
    fun shouldHide(
        declaredLanguage: String?,
        title: String,
        description: String,
        strict: Boolean = false
    ): Boolean {
        val declared = declaredLanguage?.trim()?.lowercase()
        if (!declared.isNullOrEmpty()) {
            if (declared.startsWith("uk")) return false
            if (declared.startsWith("ru")) return true
            return false        // en, pl тощо — не наша справа
        }
        return when (detectLang("$title $description")) {
            Lang.RU -> true
            Lang.UNKNOWN -> strict
            else -> false
        }
    }

    /** Сумісність зі старим викликом: рішення лише за текстом. */
    fun isRussian(title: String, description: String): Boolean =
        shouldHide(null, title, description)
}
